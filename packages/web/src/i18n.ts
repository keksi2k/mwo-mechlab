export const UI_TEXTS: Record<Locale, Record<UiKey, string>> = { en, de };

const STORAGE_KEY = 'mwo.locale';

function initialLocale(): Locale {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === 'de' || saved === 'en') return saved;
  } catch { /* optional */ }
  return navigator.language.toLowerCase().startsWith('de') ? 'de' : 'en';
}

let current: Locale = initialLocale();
document.documentElement.lang = current;

export const getLocale = () => current;
export function setLocale(l: Locale) {
  current = l;
  document.documentElement.lang = l;
  try {
    localStorage.setItem(STORAGE_KEY, l);
  } catch { /* optional */ }
}

type Params = Record<string, string | number>;
export function t(key: UiKey, params: Params = {}): string {
  return UI_TEXTS[current][key].replace(/\{(\w+)\}/g, (whole, name: string) => {
    const value = params[name];
    if (value === undefined) return whole;
    return typeof value === 'number' ? formatNumber(value, current) : value;
  });
}
export const msg = (m: Message) => formatMessage(current, m.key, m.params);
export const msgKey = (key: MessageKey) => MESSAGES[current][key];
/** Number with a fixed number of decimals, formatted for the language */
export const fixed = (n: number, digits: number) => formatFixed(n, current, digits);
export const num = (n: number, maxDigits = 2) => formatNumber(n, current, maxDigits);
export type { UiKey };
